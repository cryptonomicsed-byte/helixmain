#!/usr/bin/env python3
"""Golden vectors for canonical JSON and its SHA-256.

Python's json.dumps(sort_keys=True, separators=(",", ":"), ensure_ascii=True)
after pruning is the definition; every other language must reproduce these
strings and hashes exactly.

    python3 agent-os/contracts/conformance/generate_canonical.py
"""
import hashlib
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def prune(v):
    if isinstance(v, list):
        return [prune(x) for x in v]
    if isinstance(v, dict):
        out = {}
        for k in sorted(v):
            pv = prune(v[k])
            if pv == [] or pv == {}:
                continue
            out[k] = pv
        return out
    return v


def canonical(v):
    return json.dumps(prune(v), sort_keys=True, separators=(",", ":"))


CASES = [
    ("sorted keys, compact separators", {"b": 2, "a": 1, "c": {"y": True, "x": None}}),
    ("non-ASCII escaped, astral as a surrogate pair", {"name": "caf" + chr(0xE9) + " " + chr(0x1F600)}),
    ("quotes, backslash and whitespace escapes", {"s": "a\"b\\c\nd\re\tf"}),
    ("control characters", {"s": chr(8) + chr(12) + chr(1) + chr(0x1F) + chr(0x7F)}),
    ("empty array and object values pruned", {"keep": 1, "gone": [], "also": {}}),
    ("pruning is bottom-up", {"a": {"b": {"c": []}}, "d": 1}),
    ("empty elements inside arrays are kept", {"list": [[], {}, {"x": []}]}),
    ("integers of both signs and zero", {"n": [0, -1, 9007199254740991, -9007199254740991]}),
    ("nested arrays keep their order", {"z": [3, 1, 2], "a": [{"b": 1, "a": 2}]}),
    ("yoruba diacritics", {"name": "Ọ̀ṢỌ́"}),
    ("empty document", {}),
    ("null, booleans and empty string are values", {"a": None, "b": False, "c": ""}),
]

vectors = []
for name, value in CASES:
    text = canonical(value)
    vectors.append({"name": name, "input": value, "canonical": text,
                    "sha256": hashlib.sha256(text.encode()).hexdigest()})

import sys

document = json.dumps({"note": "Canonical JSON golden vectors. Generated by generate_canonical.py; "
                               "do not edit by hand.", "vectors": vectors}, indent=2) + "\n"
path = os.path.join(HERE, "canonical-vectors.json")
if "--check" in sys.argv:
    # the release gate: the committed vectors must be exactly what this generator produces
    if open(path).read() != document:
        sys.exit("canonical-vectors.json is not what generate_canonical.py produces: regenerate and commit it")
    print(f"{len(vectors)} canonical vectors reproduce byte for byte")
else:
    with open(path, "w") as fh:
        fh.write(document)
    print(f"wrote {len(vectors)} canonical vectors")
